/// Run a random access benchmark.
///
/// Runs the take operation repeatedly until the time limit is reached,
/// collecting timing for each run. When `reopen` is true, the accessor is
/// recreated from scratch before each iteration so that file metadata
/// parsing is included in the timing.
#[expect(clippy::too_many_arguments)]
async fn benchmark_random_access(
    dataset: &dyn BenchDataset,
    format: Format,
    measurement_name: &str,
    pattern: Option<AccessPattern>,
    indices: &[u64],
    time_limit_secs: u64,
    storage: &str,
    reopen: bool,
    io_runtime: IoRuntime,
) -> Result<RandomAccessRun> {
    let time_limit = Duration::from_secs(time_limit_secs);
    let mut runs = Vec::new();
    let mut accessor = open_accessor(dataset, format, io_runtime).await?;
    // Opening may generate or download the dataset on its first use. Keep that one-time setup out
    // of the measurement budget so cold and warm invocations collect comparable sample counts.
    let overall_start = Instant::now();

    loop {
        let start = Instant::now();
        let arr = accessor.take(indices).await?;
        runs.push(start.elapsed());
        drop(arr);

        if overall_start.elapsed() >= time_limit {
            break;
        }

        if reopen {
            accessor = open_accessor(dataset, format, io_runtime).await?;
        }
    }

    let timing = TimingMeasurement {
        name: measurement_name.to_string(),
        storage: storage.to_string(),
        target: Target::new(Engine::default(), format),
        runs,
    };
    Ok(RandomAccessRun {
        display_name: display_name(dataset.name(), pattern),
        dataset: dataset.name().to_string(),
        pattern,
        reopen,
        timing,
    })
}

/// Row label for the table view. Format is implied by the column header, so
/// it is omitted from the row label even though it stays in the
/// [`TimingMeasurement::name`] used for JSON back-compat.
fn display_name(dataset: &str, pattern: Option<AccessPattern>) -> String {
    match pattern {
        Some(p) => format!("random-access/{}/{}", dataset, p.name()),
        None => format!("random-access/{}", dataset),
    }
}

/// Build a measurement name for a benchmark run.
///
/// For taxi (legacy), the name is `random-access/{format}-{runtime}-local-disk`.
/// For other datasets, it includes the dataset and pattern:
/// `random-access/{dataset}/{pattern}/{format}-{runtime}-local-disk`.
fn measurement_name(
    dataset: &str,
    pattern: Option<AccessPattern>,
    format: Format,
    io_runtime: IoRuntime,
) -> String {
    let io_runtime = io_runtime.for_format(format);
    let fmt = format.ext();
    let runtime = io_runtime.name();
    match pattern {
        Some(p) => format!(
            "random-access/{}/{}/{}-{runtime}-local-disk",
            dataset,
            p.name(),
            fmt
        ),
        None => format!("random-access/{fmt}-{runtime}-local-disk"),
    }
}

fn v3_random_access_dataset_name(dataset: &str, pattern: Option<AccessPattern>) -> String {
    match pattern {
        Some(pattern) => format!("{dataset}/{}", pattern.name()),
        None => dataset.to_string(),
    }
}

fn push_v3_random_access_record(records: &mut Vec<v3::V3Record>, run: &RandomAccessRun) {
    if run.reopen {
        return;
    }

    let dataset = v3_random_access_dataset_name(&run.dataset, run.pattern);
    records.push(v3::random_access_record(&run.timing, &dataset));
}

/// Open a random accessor for any supported format.
///
/// For Vortex and Parquet, the path comes from [`BenchDataset::path`].
/// For Lance (behind the `lance` feature), the path is resolved from lance-bench helpers.
async fn open_accessor(
    dataset: &dyn BenchDataset,
    format: Format,
    io_runtime: IoRuntime,
) -> Result<Box<dyn RandomAccessor>> {
    let io_runtime = io_runtime.for_format(format);
    let name = format!(
        "random-access/{}/{}-{}-local-disk",
        dataset.name(),
        format.ext(),
        io_runtime.name()
    );
    match format {
        Format::OnDiskVortex | Format::VortexCompact => {
            let path = dataset.path(format).await?;
            let accessor = match io_runtime {
                IoRuntime::Tokio => VortexRandomAccessor::open(path, name, format).await?,
                IoRuntime::Compio => {
                    let handles = compio_handles()?;
                    let reader = CompioFileReadAt::open(path, handles.io).await?;
                    VortexRandomAccessor::open_source_with_session(
                        handles.session,
                        Arc::new(reader),
                        name,
                        format,
                    )
                    .await?
                }
            };
            Ok(Box::new(accessor))
        }
        Format::Parquet => {
            let path = dataset.path(format).await?;
            Ok(Box::new(ParquetRandomAccessor::open(path, name).await?))
        }
        #[cfg(feature = "lance")]
        Format::Lance => {
            use lance_bench::random_access;
            let path = match dataset.name() {
                "taxi" => random_access::taxi_data_lance().await?,
                "feature-vectors" => random_access::feature_vectors_lance().await?,
                "nested-lists" => random_access::nested_lists_lance().await?,
                "nested-structs" => random_access::nested_structs_lance().await?,
                other => anyhow::bail!("Unknown dataset for Lance: {other}"),
            };
            Ok(Box::new(
                random_access::LanceRandomAccessor::open(path, name).await?,
            ))
        }
        other => unimplemented!("open_accessor not implemented for {other}"),
    }
}

/// The benchmark ID used for output path.
const BENCHMARK_ID: &str = "random-access";

/// Repo-relative path of the suite explainer linked from CI benchmark PR comments.
const DOC_PATH: &str = "benchmarks/random-access-bench/README.md";

/// Fixed indices used by the original taxi benchmark (preserved for historical continuity).
const FIXED_TAXI_INDICES: [u64; 6] = [10, 11, 12, 13, 100_000, 3_000_000];

/// Resolved configuration for a single random-access benchmark invocation.
pub struct RunConfig {
    /// Datasets to benchmark.
    pub datasets: Vec<Box<dyn BenchDataset>>,
    /// File formats to measure for each dataset.
    pub formats: Vec<Format>,
    /// Index access patterns to measure.
    pub patterns: Vec<AccessPattern>,
    /// Maximum duration of each benchmark target in seconds.
    pub time_limit: u64,
    /// Whether each benchmark run reuses or reopens its file handle.
    pub open_mode: OpenMode,
    /// Format used to emit measurements.
    pub display_format: DisplayFormat,
    /// Optional path for the primary result output.
    pub output_path: Option<PathBuf>,
    /// Optional path for benchmark ingest JSONL records.
    pub ingest_output: Option<PathBuf>,
}

/// Run random-access benchmarks with `config`.
pub async fn run(config: RunConfig) -> Result<()> {
    let RunConfig {
        datasets,
        formats,
        patterns,
        time_limit,
        open_mode,
        display_format,
        output_path,
        ingest_output,
    } = config;
    let io_runtime = IoRuntime::from_env()?;

    let reopen_variants: &[bool] = match open_mode {
        OpenMode::Cached => &[false],
        OpenMode::Reopen => &[true],
        OpenMode::Both => &[false, true],
    };

    let total_steps: usize = datasets
        .iter()
        .map(|d| {
            let legacy_extra = if d.name() == "taxi" { formats.len() } else { 0 };
            (formats.len() * patterns.len() + legacy_extra) * reopen_variants.len()
        })
        .sum();
    let progress = ProgressBar::new(total_steps as u64);

    let mut runs: Vec<RandomAccessRun> = Vec::new();
    let mut v3_records: Vec<v3::V3Record> = Vec::new();

    // Iteration order matters for the table renderer: row order is set by the
    // first time each `(dataset, pattern)` pair is observed.
    for dataset in &datasets {
        for format in &formats {
            if dataset.name() == "taxi" {
                let name = measurement_name(dataset.name(), None, *format, io_runtime);
                for &reopen in reopen_variants {
                    let bench_name = if reopen {
                        format!("{name}-footer")
                    } else {
                        name.clone()
                    };
                    let run = benchmark_random_access(
                        dataset.as_ref(),
                        *format,
                        &bench_name,
                        None,
                        &FIXED_TAXI_INDICES,
                        time_limit,
                        STORAGE_NVME,
                        reopen,
                        io_runtime,
                    )
                    .await?;

                    push_v3_random_access_record(&mut v3_records, &run);
                    runs.push(run);
                    progress.inc(1);
                }
            }

            for pattern in &patterns {
                let indices = generate_indices(dataset.as_ref(), *pattern);
                let name = measurement_name(dataset.name(), Some(*pattern), *format, io_runtime);
                for &reopen in reopen_variants {
                    let bench_name = if reopen {
                        format!("{name}-footer")
                    } else {
                        name.clone()
                    };
                    let run = benchmark_random_access(
                        dataset.as_ref(),
                        *format,
                        &bench_name,
                        Some(*pattern),
                        &indices,
                        time_limit,
                        STORAGE_NVME,
                        reopen,
                        io_runtime,
                    )
                    .await?;

                    push_v3_random_access_record(&mut v3_records, &run);
                    runs.push(run);
                    progress.inc(1);
                }
            }
        }
    }

    progress.finish();

    if let Some(path) = ingest_output {
        v3::write_jsonl_to_path(&path, &v3_records)?;
    }

    let mut writer = create_output_writer(&display_format, output_path, BENCHMARK_ID)?;

    match display_format {
        DisplayFormat::Table => {
            render_random_access_table(&mut writer, &runs, &formats, reopen_variants)?;
        }
        DisplayFormat::GhJson => {
            let timings: Vec<TimingMeasurement> = runs.into_iter().map(|r| r.timing).collect();
            print_measurements_json(&mut writer, timings, DOC_PATH)?;
        }
    }

    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_io_runtime_values() -> Result<()> {
        assert_eq!(IoRuntime::from_str("tokio")?, IoRuntime::Tokio);
        assert_eq!(IoRuntime::from_str("compio")?, IoRuntime::Compio);
        assert!(IoRuntime::from_str("unknown").is_err());
        Ok(())
    }

    #[test]
    fn io_runtime_only_changes_vortex_measurement_names() {
        let vortex = measurement_name(
            "feature-vectors",
            Some(AccessPattern::Uniform),
            Format::OnDiskVortex,
            IoRuntime::Compio,
        );
        let parquet = measurement_name(
            "feature-vectors",
            Some(AccessPattern::Uniform),
            Format::Parquet,
            IoRuntime::Compio,
        );
        assert!(vortex.ends_with("vortex-compio-local-disk"));
        assert!(parquet.ends_with("parquet-tokio-local-disk"));
    }

    #[test]
    fn v3_random_access_dataset_names_match_schema_dims() {
        assert_eq!(v3_random_access_dataset_name("taxi", None), "taxi");
        assert_eq!(
            v3_random_access_dataset_name("taxi", Some(AccessPattern::Correlated)),
            "taxi/correlated"
        );
        assert_eq!(
            v3_random_access_dataset_name("feature-vectors", Some(AccessPattern::Uniform)),
            "feature-vectors/uniform"
        );
    }

    fn fake_run(dataset: &str, pattern: Option<AccessPattern>, reopen: bool) -> RandomAccessRun {
        RandomAccessRun {
            timing: TimingMeasurement {
                name: format!("random-access/{dataset}/parquet-tokio-local-disk"),
                target: Target::new(Engine::Vortex, Format::Parquet),
                storage: STORAGE_NVME.to_string(),
                runs: vec![Duration::from_nanos(10)],
            },
            dataset: dataset.to_string(),
            pattern,
            reopen,
            display_name: display_name(dataset, pattern),
        }
    }

    #[test]
    fn v3_random_access_records_skip_reopen_variants() {
        let mut records = Vec::new();

        push_v3_random_access_record(&mut records, &fake_run("taxi", None, false));
        push_v3_random_access_record(
            &mut records,
            &fake_run("taxi", Some(AccessPattern::Uniform), false),
        );
        push_v3_random_access_record(
            &mut records,
            &fake_run("taxi", Some(AccessPattern::Correlated), true),
        );

        assert_eq!(records.len(), 2);
        match &records[0] {
            v3::V3Record::RandomAccessTime(record) => assert_eq!(record.dataset, "taxi"),
            other => panic!("expected random-access record, got {other:?}"),
        }
        match &records[1] {
            v3::V3Record::RandomAccessTime(record) => assert_eq!(record.dataset, "taxi/uniform"),
            other => panic!("expected random-access record, got {other:?}"),
        }
    }

    #[test]
    fn display_name_drops_format_extension() {
        assert_eq!(display_name("taxi", None), "random-access/taxi");
        assert_eq!(
            display_name("taxi", Some(AccessPattern::Uniform)),
            "random-access/taxi/uniform"
        );
        assert_eq!(
            display_name("feature-vectors", Some(AccessPattern::Correlated)),
            "random-access/feature-vectors/correlated"
        );
    }
}
